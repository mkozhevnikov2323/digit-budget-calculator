/**
 * Возвращает сегодняшнюю дату в формате YYYY-MM-DD (для type="date" инпутов).
 *
 * Важно: значение вычисляется в момент вызова, а не один раз при монтировании —
 * используйте эту функцию напрямую в reset()/defaultValues, а не кэшируйте
 * результат в замыкании, иначе дата "залипнет" на момент первого рендера.
 *
 * @returns строка вида "2024-05-01"
 */
export const getTodayDateString = (): string =>
  new Date().toISOString().slice(0, 10);

/**
 * Собирает значения для reset() формы после успешного сабмита так, чтобы
 * поле даты НЕ сбрасывалось на "сегодня", а оставалось тем, что пользователь
 * только что ввёл. Удобно, когда нужно добавить подряд несколько операций
 * за один и тот же (в том числе прошедший) день — не приходится каждый раз
 * заново выбирать дату.
 *
 * @param emptyValues - значения формы без поля date (обнуляются как обычно)
 * @param submittedDate - дата из только что отправленных данных формы
 * @returns объект значений для reset(), где все поля пустые, а date = submittedDate
 */
export const buildResetValuesKeepingDate = <T extends { date: string }>(
  emptyValues: Omit<T, 'date'>,
  submittedDate: string,
): T => ({ ...emptyValues, date: submittedDate }) as T;
